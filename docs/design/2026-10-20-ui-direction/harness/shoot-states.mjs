// Row menu, saved-view popovers and drawer edit mode, as the admin.
import { chromium } from 'playwright-core';
const R = process.argv[2];
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, storageState: '/tmp/ui-env/state-admin.json' });
const page = await context.newPage();
await page.addInitScript(() => { document.addEventListener('DOMContentLoaded', () => { const s = document.createElement('style'); s.textContent = 'nextjs-portal{display:none!important}'; document.head.appendChild(s); }); });
await page.goto('http://localhost:3300/workspace/nebula-demo/objects/customers', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: '更多操作 客户 赵晨-1' }).click();
await page.getByRole('menuitem', { name: '查看' }).waitFor();
await page.waitForTimeout(500);
await page.screenshot({ path: `${R}/row-menu.png` });
await page.keyboard.press('Escape');
await page.getByRole('button', { name: '保存为视图' }).click();
await page.getByRole('textbox', { name: '视图名称' }).fill('制造业 A 级客户');
await page.waitForTimeout(400);
await page.screenshot({ path: `${R}/save-view.png` });
await page.getByRole('button', { name: '保存视图' }).click();
await page.getByRole('button', { name: /我的视图/ }).click();
await page.getByRole('list', { name: '已保存的视图' }).waitFor();
await page.waitForTimeout(400);
await page.screenshot({ path: `${R}/view-list.png` });
await page.keyboard.press('Escape');
await page.getByRole('link', { name: '客户 赵晨-1' }).first().click();
const drawer = page.getByRole('dialog').first();
await drawer.waitFor();
await page.waitForTimeout(800);
await page.screenshot({ path: `${R}/drawer-admin.png` });
await drawer.getByRole('button', { name: /^编\s*辑$/ }).click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${R}/drawer-edit.png` });
await browser.close();
